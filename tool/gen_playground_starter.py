#!/usr/bin/env python3
"""Builds assets/playground/starter.yaml, the first example the docs-site
playground loads: one page that shows the four main kinds of content
together — prose, a table, a flowchart and a calculator.

It is assembled, not written: the Paediatric Sepsis page (prose, SIRS table,
algorithm flowchart) verbatim, plus the Holliday-Segar maintenance-fluids
calculator block from the Calculators book, so the clinical text stays the
book's own and any correction to either source lands here on the next run.
test/schema/schema_test.dart fails when this file is older than its sources.

Run from the repo root:  python3 tool/gen_playground_starter.py
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEPSIS = ROOT / 'assets/books/protocolbook/topics/pb_045_paediatric_sepsis.yaml'
FLUIDS = ROOT / 'assets/books/calculators/topics/calc_holliday_segar.yaml'
OUT = ROOT / 'assets/playground/starter.yaml'

sepsis = SEPSIS.read_text()
fluids = FLUIDS.read_text()

# The sepsis page from `topic:` on, with its header fields renamed for the
# sampler (structural YAML keys, case-sensitive on purpose).
body = sepsis[sepsis.index('topic:\n'):]
body = re.sub(r'^  id: .*$', '  id: "playground-sampler"', body, count=1, flags=re.M)
body = re.sub(r'^  title: .*$', '  title: "Paediatric Sepsis & Septic Shock (sampler)"', body, count=1, flags=re.M)
body = re.sub(r'^  list_subtitle: .*$', '  list_subtitle: "prose · table · flowchart · calculator"', body, count=1, flags=re.M)
body = re.sub(r'^  page_number: .*\n', '', body, count=1, flags=re.M)

# The formula block: from its `- type: "formula"` line to the end of the file.
m = re.search(r'^    - type: "formula"\n', fluids, re.M)
if not m:
    sys.exit('formula block not found in ' + str(FLUIDS))
formula = fluids[m.start():].rstrip() + '\n'

header = '''# ============================================================
# Playground sampler — one page with the four main kinds of content:
# prose, a table, a flowchart and a calculator.
#
# GENERATED by tool/gen_playground_starter.py from two real pages; edit
# those, then re-run the script:
#   assets/books/protocolbook/topics/pb_045_paediatric_sepsis.yaml
#     (ProtocolBook p.45 — the prose, the SIRS table, the algorithm)
#   assets/books/calculators/topics/calc_holliday_segar.yaml
#     (the maintenance-fluids calculator block)
# ============================================================

'''
calc_note = '''
    # ── Calculator block, from the Calculators book (Maintenance IV Fluids) ──
'''
OUT.write_text(header + body.rstrip() + '\n' + calc_note + formula)
print(f'wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)', flush=True)
