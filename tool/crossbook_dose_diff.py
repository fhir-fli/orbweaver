#!/usr/bin/env python3
"""Stage 2 of the cross-book dose comparison.

Reads tool/crossbook/doses.tsv and, for every drug that appears in BOTH books,
lays the two books' doses side by side per unit. Where the two books' value
sets for one unit are not identical, the drug+unit is written to a candidates
file for adjudication by hand.

This narrows; it does not decide. A difference is not a contradiction — the
two books legitimately dose the same drug differently for different
indications, and one is paediatric throughout while the other is not. Every
candidate has to be read against its context before it becomes a flag.

Both outputs are written and flushed per drug.
"""

import io
import os
import re
import sys
from collections import defaultdict

OUTDIR = '/home/grey/dev/fhir/orbweaver/tool/crossbook'
SRC = os.path.join(OUTDIR, 'doses.tsv')
FULL = os.path.join(OUTDIR, 'side_by_side.md')
CAND = os.path.join(OUTDIR, 'candidates.md')

# Units that describe a preparation or a volume rather than a dose. They are
# kept in the full sheet but never raise a candidate on their own: "2 ml vial"
# and "0.3 ml" differ between books for reasons that are not clinical.
WEAK_UNITS = {'ml', 'ml/hr', 'ml/h', 'mg/ml', 'mcg/ml', 'gm', 'mmhg', 'µg/l',
              'mmol/l'}


def norm_value(v):
    """Normalise a numeric value or range for comparison.

    The print uses hyphens in ranges and the app uses en-dashes, and decimal
    commas appear in a handful of places. Both cost false differences.
    """
    v = re.sub(r'[‐-―−]', '-', v)
    # Thousands separators first — "50 000" and "50,000" are the same dose,
    # written differently in the two books. Only then treat a comma as a
    # decimal point (a handful of places use the European form).
    v = re.sub(r'(?<=\d)[ \u00a0,](?=\d{3}(?!\d))', '', v)
    v = v.replace(',', '.').replace(' ', '')
    parts = [p for p in v.split('-') if p]
    out = []
    for p in parts:
        try:
            f = float(p)
        except ValueError:
            out.append(p)
            continue
        out.append(('%g' % f))
    return '-'.join(out)


def main():
    if not os.path.exists(SRC):
        print('missing %s — run crossbook_dose_extract.py first' % SRC)
        return 1

    # drug -> book -> unit -> value -> list of (freq, topic, context, fragment)
    data = defaultdict(lambda: defaultdict(lambda: defaultdict(
        lambda: defaultdict(list))))
    with io.open(SRC, encoding='utf-8') as f:
        header = next(f)
        for line in f:
            cols = line.rstrip('\n').split('\t')
            if len(cols) < 9:
                continue
            book, fname, topic, drug, value, unit, freq, ctx, frag = cols[:9]
            data[drug][book][unit][norm_value(value)].append(
                (freq, topic, ctx, frag))

    drugs = sorted(data)
    both = [d for d in drugs if 'PB' in data[d] and 'WHO' in data[d]]
    only_pb = [d for d in drugs if 'WHO' not in data[d]]
    only_who = [d for d in drugs if 'PB' not in data[d]]

    print('%d drugs total · %d in BOTH books · %d ProtocolBook only · '
          '%d WHO only' % (len(drugs), len(both), len(only_pb), len(only_who)),
          flush=True)

    ff = io.open(FULL, 'w', encoding='utf-8')
    cf = io.open(CAND, 'w', encoding='utf-8')

    ff.write('# Cross-book dose comparison — every drug in both books\n\n')
    ff.write('Generated by `tool/crossbook_dose_diff.py` from '
             '`tool/crossbook/doses.tsv`.\n\n')
    ff.write('**%d drugs carry a dose in both books.** For each, every distinct '
             'value is listed per unit,\nwith the topic it came from. A '
             'difference is NOT a contradiction — read the context.\n\n'
             % len(both))
    ff.flush()

    cf.write('# Cross-book dose candidates — where the two books differ\n\n')
    cf.write('Generated by `tool/crossbook_dose_diff.py`. **These are '
             'candidates, not findings.**\nThe two books legitimately dose the '
             'same drug differently for different indications,\nand one is '
             'paediatric throughout. Every line below has to be read against '
             'its\ncontext before it becomes a flag.\n\n')
    cf.flush()

    n_cand = 0
    cand_drugs = 0
    for drug in both:
        pb = data[drug]['PB']
        who = data[drug]['WHO']
        units = sorted(set(pb) | set(who))

        ff.write('## %s\n\n' % drug)
        drug_cands = []
        for unit in units:
            pv = set(pb.get(unit, {}))
            wv = set(who.get(unit, {}))
            if not pv or not wv:
                continue
            mark = ''
            if pv != wv and unit not in WEAK_UNITS:
                mark = '  ⚠️'
                drug_cands.append((unit, sorted(pv - wv), sorted(wv - pv),
                                   sorted(pv & wv)))
            ff.write('**%s**%s\n' % (unit, mark))
            ff.write('- PB: %s\n' % ', '.join(sorted(pv, key=_k)))
            ff.write('- WHO: %s\n' % ', '.join(sorted(wv, key=_k)))
            ff.write('\n')
        ff.flush()

        if drug_cands:
            cand_drugs += 1
            cf.write('## %s\n\n' % drug)
            for unit, only_p, only_w, shared in drug_cands:
                n_cand += 1
                cf.write('### %s %s\n\n' % (drug, unit))
                if shared:
                    cf.write('Shared: %s\n\n'
                             % ', '.join(sorted(shared, key=_k)))
                if only_p:
                    cf.write('**ProtocolBook only:** %s\n\n'
                             % ', '.join(sorted(only_p, key=_k)))
                    for v in sorted(only_p, key=_k):
                        for freq, topic, ctx, frag in pb[unit][v][:2]:
                            cf.write('- `%s %s` %s — *%s* › %s\n  > %s\n'
                                     % (v, unit, ('(%s)' % freq) if freq else '',
                                        topic, ctx, frag[:220]))
                    cf.write('\n')
                if only_w:
                    cf.write('**WHO only:** %s\n\n'
                             % ', '.join(sorted(only_w, key=_k)))
                    for v in sorted(only_w, key=_k):
                        for freq, topic, ctx, frag in who[unit][v][:2]:
                            cf.write('- `%s %s` %s — *%s* › %s\n  > %s\n'
                                     % (v, unit, ('(%s)' % freq) if freq else '',
                                        topic, ctx, frag[:220]))
                    cf.write('\n')
            cf.flush()
        print('%s: %d units compared, %d candidate units'
              % (drug, len(units), len(drug_cands)), flush=True)

    ff.write('\n---\n\n## Drugs dosed in only one book\n\n')
    ff.write('**ProtocolBook only (%d):** %s\n\n'
             % (len(only_pb), ', '.join(only_pb)))
    ff.write('**WHO only (%d):** %s\n\n'
             % (len(only_who), ', '.join(only_who)))
    ff.close()

    cf.write('\n---\n\n**%d candidate drug+unit pairs across %d drugs.**\n'
             % (n_cand, cand_drugs))
    cf.close()
    print('DONE: %d candidate drug+unit pairs across %d drugs -> %s'
          % (n_cand, cand_drugs, CAND), flush=True)
    return 0


def _k(v):
    try:
        return (0, float(v.split('-')[0]))
    except ValueError:
        return (1, 0.0)


if __name__ == '__main__':
    sys.exit(main())
