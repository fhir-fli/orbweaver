import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:orbweaver/services/app_version.dart';
import 'package:orbweaver/services/feedback_email.dart';

/// Guards on the feedback email.
///
/// The point of the feature is that a report arrives already saying WHICH page
/// and WHICH build it came from, and lands in a folder. Each of these fails if
/// one of those stops being true.
void main() {
  const ctx = FeedbackContext(
    bookId: 'who_imci',
    bookTitle: 'Hospital Care for Children',
    topicId: 'who_6_02_1_severe_malaria',
    topicTitle: 'Severe Malaria',
    pageLabel: 'p.23',
  );

  test('the subject starts with the filter tag', () {
    // A mail rule keys on this. If it changes, every existing filter breaks.
    expect(buildSubject(ctx), startsWith(kFeedbackSubjectTag));
    expect(buildSubject(ctx), contains('who_6_02_1_severe_malaria'));
  });

  test('a report with no topic still sorts', () {
    expect(buildSubject(const FeedbackContext()), '$kFeedbackSubjectTag general');
    expect(buildSubject(const FeedbackContext(bookId: 'wvems')),
        '$kFeedbackSubjectTag wvems');
  });

  test('the body carries page, book, topic and build', () {
    final body = buildBody(ctx, now: DateTime.utc(2026, 9, 3, 12));
    expect(body, contains('who_imci'));
    expect(body, contains('who_6_02_1_severe_malaria'));
    expect(body, contains('Severe Malaria'));
    expect(body, contains('p.23'));
    expect(body, contains(kAppVersion));
    expect(body, contains('2026-09-03T12:00:00.000Z'));
  });

  test('the reader writes above the fence, metadata sits below it', () {
    final body = buildBody(ctx);
    final fence = body.indexOf(kMetadataFence);
    expect(fence, greaterThan(0));
    expect(body.indexOf('who_6_02_1_severe_malaria'), greaterThan(fence));
  });

  test('optional fields are omitted rather than printed empty', () {
    final body = buildBody(const FeedbackContext(bookId: 'wvems'));
    expect(body, isNot(contains('topic ')));
    expect(body, isNot(contains('page ')));
    expect(body, contains('wvems'));
  });

  test('the mailto encodes spaces as %20, never as +', () {
    // Uri(queryParameters:) encodes a space as '+', and several mail clients
    // then render literal plus signs through the whole body.
    final uri = buildFeedbackUri(ctx, now: DateTime.utc(2026, 9, 3));
    expect(uri.scheme, 'mailto');
    expect(uri.path, kFeedbackAddress);
    final q = uri.query;
    expect(q, contains('%20'));
    expect(q.contains('+'), isFalse,
        reason: 'a + in the query will show as a literal + in the mail body');
    expect(q, contains('%0A'), reason: 'newlines must survive encoding');
  });

  test('the generated version constant matches pubspec', () {
    // lib/services/app_version.dart is generated by tool/gen_version.dart.
    // This fails if the version is bumped and the constant is not regenerated,
    // which would make every report name the wrong build.
    final pubspec = File('pubspec.yaml').readAsStringSync();
    final m = RegExp(r'^version:\s*(\S+)', multiLine: true).firstMatch(pubspec);
    expect(m, isNotNull);
    expect(kAppVersion, m!.group(1),
        reason: 'run: dart run tool/gen_version.dart');
  });
}
